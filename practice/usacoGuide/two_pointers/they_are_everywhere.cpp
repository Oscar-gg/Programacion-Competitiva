int count(vector<int> &types)
{
    int t = 0;
    for (auto v : types)
    {
        if (v > 0)
            t++;
    }
    return t;
}

void s()
{
    int n;
    string s;
    cin >> n >> s;

    vector<int> types(58);
    for (auto c : s)
    {
        types[c - 'A']++;
    }
    int tar = count(types);

    types = vector<int>(58);

    int l = 0, r = 0, ans = INT_MAX;

    while (r < n)
    {
        types[s[r] - 'A']++;

        while (count(types) == tar)
        {
            ans = min(ans, r - l + 1);
            types[s[l] - 'A']--;
            l++;
        }
        r++;
    }

    cout << ans << "\n";
}

